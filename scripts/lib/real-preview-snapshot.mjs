const q = (s) => `"${String(s).replaceAll('"', '""')}"`;
const hasPrivateText = (s) => /https?:\/\/|@|(?:\+?82[- ]?)?01[016789][- ]?\d{3,4}[- ]?\d{4}|0[2-6]\d?[- ]?\d{3,4}[- ]?\d{4}|\d{2,4}[- ]\d{3,4}[- ]\d{4}|(?:로|길)\s*\d|\d+동(?:\s*\d+호)?|[가-힣]+(?:동|읍|면|리)\s*\d+(?:-\d+)?/.test(s);
const hasPossibleBirthDate = (s) => /(?:19|20)\d{2}[-./]\d{1,2}[-./]\d{1,2}|\b(?:19|20)\d{6}\b/.test(s);
const isBusinessKey = (key) => /^(?:id|.*Id|.*Ids|sessionKey|slotKey|slotKeys|selectedSlotKeysJSON|registrationMonth|serviceMonth|monthLabel|dayKey)$/.test(key);
const JSON_DISPLAY_KEYS = new Set(['label', 'name', 'studentName', 'stopName', 'grade', 'childGrade', 'gradeRange']);

// 공개 URL만 남기며 서명·인증·개인정보가 포함된 주소는 복사하지 않습니다.
export function sanitizePublicPreviewUrl(value) {
  if (typeof value !== 'string' || !value.trim() || value.includes('\\')) return null;
  const raw = value.trim();
  if (/^\/(?:uploads|images)\/[A-Za-z0-9_./%-]+$/.test(raw) && !raw.includes('..') && !/private|token|secret/i.test(raw)) return raw;
  try {
    const url = new URL(raw);
    if (url.protocol !== 'https:' || url.username || url.password || url.port || url.hash) return null;
    if (/token|secret|signature|credential|auth|key|private|session/i.test(url.pathname)) return null;
    const host = url.hostname.toLowerCase();
    if (host.endsWith('.supabase.co')) {
      if (!url.pathname.startsWith('/storage/v1/object/public/') || url.search) return null;
      return url.toString();
    }
    const allowed = new Set(['stiz.kr', 'www.stiz.kr', 'www.stiz-dasan.kr', 'stiz-dasan.kr', 'images.unsplash.com', 'www.youtube.com', 'youtube.com', 'youtu.be', 'www.instagram.com', 'instagram.com', 'pf.kakao.com', 'place.naver.com', 'm.place.naver.com', 'naver.me', 'forms.gle', 'docs.google.com']);
    if (!allowed.has(host)) return null;
    if (host === 'docs.google.com' && !/^\/forms\/d\/e\/[A-Za-z0-9_-]+\/viewform$/.test(url.pathname)) return null;
    // YouTube 동영상 ID와 공개 폼의 고정 표시 옵션만 허용합니다.
    for (const [key, entry] of url.searchParams) {
      if (!(key === 'v' && /^(?:www\.)?youtube\.com$/.test(host) && /^[A-Za-z0-9_-]{11}$/.test(entry)) && !(host === 'docs.google.com' && key === 'embedded' && entry === 'true')) return null;
    }
    return url.toString();
  } catch { return null; }
}

const PUBLIC_URL_FIELDS = new Set(['imageUrl', 'trialFormUrl', 'enrollFormUrl', 'youtubeUrl', 'instagramUrl', 'kakaoChannelUrl', 'naverPlaceUrl', 'uniformFormUrl']);
const PUBLIC_MEDIA_FIELDS = new Set(['mediaJSON', 'facilitiesImagesJSON', 'galleryImagesJSON']);
function sanitizePublicMedia(value, stats) {
  try {
    const parsed = typeof value === 'string' ? JSON.parse(value) : value;
    if (!Array.isArray(parsed)) return '[]';
    return JSON.stringify(parsed.flatMap((entry) => {
      const url = sanitizePublicPreviewUrl(typeof entry === 'string' ? entry : entry?.url);
      if (!url) { stats.jsonFieldsRemoved++; return []; }
      if (typeof entry === 'string') return [url];
      return [{ type: entry.type === 'video' ? 'video' : 'image', url }];
    }));
  } catch { stats.jsonFieldsRemoved++; return '[]'; }
}

function sanitizeJson(value, stats, field = '') {
  if (Array.isArray(value)) return value.map((v) => sanitizeJson(v, stats, field));
  if (value && typeof value === 'object') {
    const out = {};
    for (const [key, entry] of Object.entries(value)) {
      if (JSON_KEYS.has(key)) out[key] = sanitizeJson(entry, stats, key);
      else stats.jsonFieldsRemoved++;
    }
    return out;
  }
  if (typeof value === 'string' && !isBusinessKey(field) && (hasPrivateText(value) || (JSON_DISPLAY_KEYS.has(field) && hasPossibleBirthDate(value)))) {
    stats.textFieldsMasked++;
    return '비공개';
  }
  return value;
}

function serviceMonths(now) {
  const date = new Date(now);
  if (Number.isNaN(date.getTime())) throw new Error('미리보기 기준일이 올바르지 않습니다.');
  const korea = new Date(date.getTime() + 9 * 3600_000);
  const year = korea.getUTCFullYear(), month = korea.getUTCMonth();
  const ym = (offset) => new Date(Date.UTC(year, month + offset, 1)).toISOString().slice(0, 7);
  const start = (offset) => new Date(Date.UTC(year, month + offset, 1) - 9 * 3600_000);
  return { previous: ym(-1), current: ym(0), next: ym(1), from: start(-1), to: start(1) };
}

/** 연결·트랜잭션·파일 저장은 호출자가 담당한다. 이 함수는 SELECT만 실행한다. */
export async function capturePreviewSnapshot(sourceClient, { now = new Date(), adminEmail = 'cobby8@stiz.kr', calendarEvents = [] } = {}) {
  const window = serviceMonths(now);
  const metadata = await sourceClient.query(`SELECT table_name, column_name, is_nullable, data_type FROM information_schema.columns WHERE table_schema = 'public' AND table_name = ANY($1::text[])`, [Object.keys(FIELDS)]);
  const schema = new Map();
  for (const row of metadata.rows) {
    if (!schema.has(row.table_name)) schema.set(row.table_name, new Map());
    schema.get(row.table_name).set(row.column_name, row);
  }
  if (!schema.get('User')?.has('email')) throw new Error('관리자 계정 확인에 필요한 자료가 없습니다.');
  // 이메일은 조건으로만 사용한다. 원본 이메일/인증 식별자를 SELECT하지 않는다.
  const selected = await sourceClient.query('SELECT "id", "role" FROM "public"."User" WHERE lower("email") = lower($1) LIMIT 2', [adminEmail]);
  if (selected.rows.length !== 1 || !['ADMIN', 'VICE_ADMIN'].includes(selected.rows[0].role)) throw new Error('미리보기 관리자 계정을 확인하지 못했습니다.');
  const adminId = selected.rows[0].id;
  const stats = { phonesMasked: 0, birthDatesMasked: 0, emailsReplaced: 0, authIdsReplaced: 0, jsonFieldsRemoved: 0, textFieldsMasked: 0, requestBodiesReplaced: 0, omittedTables: [], omittedColumns: 0 };
  const tables = [], byName = new Map();
  async function read(name, where = '', params = [], suffix = '') {
    const cols = schema.get(name);
    if (!cols) { stats.omittedTables.push(name); return []; }
    // 필터 컬럼이 없는 옛 DB를 무범위 조회로 바꾸지 않고 해당 표만 생략한다.
    if ([...(where + suffix).matchAll(/"([A-Za-z][A-Za-z0-9]*)"/g)].some((match) => !cols.has(match[1]))) {
      stats.omittedTables.push(name);
      return [];
    }
    const fields = FIELDS[name].split(' ').filter((field) => cols.has(field));
    stats.omittedColumns += FIELDS[name].split(' ').length - fields.length;
    const expressions = fields.map((field) => {
      if (/phone$/i.test(field)) return `CASE WHEN ${q(field)} IS NULL THEN NULL ELSE '${PRIVATE_PHONE}' END AS ${q(field)}`;
      if (/birthDate$/i.test(field)) return `CASE WHEN ${q(field)} IS NULL THEN NULL ELSE TIMESTAMP '2000-01-01 00:00:00' END AS ${q(field)}`;
      if (name === 'RegularAbsence' && field === 'reason') return `CASE WHEN "reason" IN ('ILLNESS_INJURY', 'PERSONAL', 'FAMILY_TRIP', 'SCHOOL_EVENT', 'ETC') THEN "reason" ELSE 'ETC' END AS "reason"`;
      // 실제 요청 본문처럼 보이지 않도록 명시적인 가림 문구만 넣는다.
      if (name === 'ParentRequest' && field === 'title') return `'학부모 요청' AS "title"`;
      if (name === 'ParentRequest' && field === 'content') return `'비공개' AS "content"`;
      if (name === 'User' && field === 'username') return `(${q(field)} IS NOT NULL) AS "__hasUsername"`;
      return q(field);
    });
    if (!expressions.length) return [];
    const result = await sourceClient.query(`SELECT ${expressions.join(', ')} FROM "public".${q(name)}${where ? ` WHERE ${where}` : ''}${suffix}`, params);
    const rows = result.rows.map((original) => {
      const row = { ...original };
      for (const key of Object.keys(row)) {
        if (PUBLIC_URL_FIELDS.has(key)) { row[key] = sanitizePublicPreviewUrl(row[key]); continue; }
        if (PUBLIC_MEDIA_FIELDS.has(key)) { row[key] = sanitizePublicMedia(row[key], stats); continue; }
        if (/phone$/i.test(key) && row[key] !== null) stats.phonesMasked++;
        if (/birthDate$/i.test(key) && row[key] !== null) stats.birthDatesMasked++;
        if (['slotsJson', 'gradesJSON', 'selectedSlotKeysJSON'].includes(key) && typeof row[key] === 'string') {
          try { row[key] = JSON.stringify(sanitizeJson(JSON.parse(row[key]), stats, key)); }
          catch { row[key] = '[]'; stats.jsonFieldsRemoved++; }
        } else if (key === 'payload') row[key] = sanitizeJson(row[key], stats);
        else if (typeof row[key] === 'string' && !isBusinessKey(key) && hasPrivateText(row[key])) { row[key] = '비공개'; stats.textFieldsMasked++; }
      }
      if (name === 'User') {
        row.email = `user-${randomUUID()}@preview.invalid`;
        row.authUserId = randomUUID();
        if ('__hasUsername' in row) { row.username = row.__hasUsername ? `preview-${randomUUID()}` : null; delete row.__hasUsername; }
        stats.emailsReplaced++; stats.authIdsReplaced++;
      }
      if (name === 'PaymentInvoice') row.invoiceNo = `PREVIEW-${randomUUID()}`;
      if (name === 'ParentRequest') stats.requestBodiesReplaced++;
      return row;
    });
    tables.push({ name, rows }); byName.set(name, rows);
    return rows;
  }
  for (const name of ['User', 'Student', 'Program', 'Coach', 'Class', 'Enrollment', 'ClassSlotOverride', 'CustomClassSlot', 'ScheduleSlot', 'SheetSlotCache', 'TrialLead', 'EnrollmentApplication', 'EnrollmentChangeRequest', 'ParentRequest', 'ApplicationContactLog', 'AcademySettings', 'ShuttleVehicle', 'AnnualEvent']) await read(name);
  // 공개 판정 컬럼이 없는 옛 DB는 무조건 조회하지 않고 해당 표를 생략합니다.
  await read('Notice', '"targetType" = $1', ['ALL'], ' ORDER BY "createdAt" DESC LIMIT 30');
  await read('GalleryPost', '"isPublic" = true', [], ' ORDER BY "createdAt" DESC LIMIT 24');
  for (const name of ['Testimonial', 'Faq']) await read(name, '"isPublic" = true', [], ' ORDER BY "order" ASC LIMIT 100');
  const annual = byName.get('AnnualEvent');
  if (annual && calendarEvents.length) for (const event of calendarEvents) {
    annual.push({ id: event.id, title: hasPrivateText(event.title) ? '비공개' : event.title, date: event.date, endDate: event.endDate, category: event.category, createdAt: event.createdAt, updatedAt: event.updatedAt });
  }
  // 장부는 YYYY-MM / YYYY년 M월 등 실제 쓰이는 표기를 같은 월로 비교한다.
  const ledgerHasMonth = schema.get('StudentRegistrationLedger')?.has('registrationMonth');
  const monthParts = window.current.split('-').map(Number);
  const ledgers = await read('StudentRegistrationLedger', ledgerHasMonth ? `regexp_replace("registrationMonth", '[^0-9]', '', 'g') = ANY($1::text[])` : 'FALSE', ledgerHasMonth ? [[`${monthParts[0]}${String(monthParts[1]).padStart(2, '0')}`, `${monthParts[0]}${monthParts[1]}`]] : []);
  const batchIds = [...new Set(ledgers.map((r) => r.batchId).filter(Boolean))];
  await read('StudentSheetImportBatch', '"id" = ANY($1::text[])', [batchIds]);
  const sessions = await read('Session', '"date" >= $1 AND "date" < $2', [window.from, window.to]);
  await read('Attendance', '"sessionId" = ANY($1::text[])', [sessions.map((r) => r.id)]);
  await read('RegularAbsence', '"date" >= $1 AND "date" < $2', [window.from, window.to]);
  const paymentHasMonth = schema.get('Payment')?.has('month') && schema.get('Payment')?.has('year');
  const previousParts = window.previous.split('-').map(Number);
  const payments = await read('Payment', paymentHasMonth ? '( ("year" = $3 AND "month" = $4) OR ("year" = $5 AND "month" = $6) OR (("year" IS NULL OR "month" IS NULL) AND "dueDate" >= $1 AND "dueDate" < $2) )' : '"dueDate" >= $1 AND "dueDate" < $2', paymentHasMonth ? [window.from, window.to, ...previousParts, ...monthParts] : [window.from, window.to]);
  await read('PaymentInvoice', '"paymentId" = ANY($1::text[])', [payments.map((r) => r.id)]);
  for (const name of ['RegularShuttleStop', 'RegularDispatchRoute']) await read(name, '"serviceMonth" = ANY($1::text[])', [[window.current, window.next]]);
  const users = byName.get('User') ?? [];
  const viewAccount = (row) => row ? { id: row.id, email: row.email, authId: row.authUserId } : undefined;
  const admin = users.find((row) => row.id === adminId);
  if (!admin) throw new Error('미리보기 관리자 자료가 없습니다.');
  const instructorIds = new Set((byName.get('Class') ?? []).map((row) => row.instructorId));
  const coachUserIds = new Set((byName.get('Coach') ?? []).map((row) => row.userId));
  const parentIds = new Set((byName.get('Student') ?? []).map((row) => row.parentId));
  const teacher = users.find((row) => row.id === adminId && (instructorIds.has(row.id) || coachUserIds.has(row.id))) ?? users.find((row) => row.role === 'INSTRUCTOR' && (instructorIds.has(row.id) || coachUserIds.has(row.id)));
  const parent = users.find((row) => row.id === adminId && parentIds.has(row.id)) ?? users.find((row) => parentIds.has(row.id));
  return {
    tables,
    summary: { tablecounts: Object.fromEntries(tables.map(({ name, rows }) => [name, rows.length])), timewindow: { lessonsFrom: window.from.toISOString(), lessonsBefore: window.to.toISOString(), registrationMonth: window.current, shuttleMonths: [window.current, window.next] }, redactions: stats },
    accounts: { admin: viewAccount(admin), ...(teacher ? { teacher: viewAccount(teacher) } : {}), ...(parent ? { parent: viewAccount(parent) } : {}) },
  };
}
