/**
 * 학부모 계정을 찾을 때 쓰는 전화번호 규칙.
 *
 * ■ 왜 필요한가 — 저장 형식이 두 가지로 섞여 있다
 *   · 가입(`parent-signup-verification`)은 숫자만 저장한다: `01012345678`
 *   · 신청서(`actions/public.ts`)는 하이픈을 넣어 저장한다: `010-1234-5678`
 *   2026-09-18 실측: 학부모 계정 314개 중 284개(90%)가 숫자만이다.
 *   그래서 "글자 그대로" 비교하면 **번호가 바뀌지 않아도 기존 학부모를 못 찾고**
 *   계정과 학생을 새로 만든다. 8~9월에 4가족이 이렇게 갈라져
 *   학부모가 로그인해도 자녀가 0명으로 보였다.
 *
 * ■ 빈 번호끼리 서로 매칭되면 더 큰 사고다
 *   번호가 비어 있는 학부모 계정이 20개 있다. 숫자만 남기면 전부 빈 문자열이 되어
 *   서로 같은 사람으로 묶인다. 남의 자녀가 붙는 일이라 반드시 막는다.
 */

/** 전화번호에서 숫자만 남긴다. 비교는 항상 이 값으로 한다. */
export function parentPhoneDigits(raw: unknown): string {
  return String(raw ?? "").replace(/[^0-9]/g, "");
}

/**
 * 이 번호를 "사람을 찾는 열쇠"로 써도 되는가.
 * 비었거나 너무 짧거나 0·같은 숫자만 반복되는 자리채움 번호는 열쇠로 쓰지 않는다.
 * (시트 임포트가 번호 없는 학부모에게 `00000000000` 을 넣어둔 전례가 있다)
 */
export function isUsablePhoneKey(digits: string): boolean {
  if (!/^[0-9]{9,11}$/.test(digits)) return false;
  if (/^(\d)\1+$/.test(digits)) return false; // 00000000000, 11111111111 …
  return true;
}
