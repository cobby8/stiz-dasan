export function userFacingError(error: unknown, fallback: string): string {
  if (!(error instanceof Error)) return fallback;
  const message = error.message;
  if (message === "Staff permission is required.") return "선생님 권한이 필요합니다.";
  if (message === "원장 권한이 필요합니다. (ADMIN만 가능)") return "원장 권한이 필요합니다.";
  if (BUSINESS_MESSAGES.has(message)) return message;
  // 수강 변경 안내의 가변 값은 날짜와 건수만 허용한다. 임의의 본문·식별자는 통과하지 않는다.
  if (/^적용일\((?:20\d{2}-\d{2}-\d{2}|미확정)\) 이전에는 (?:홈페이지 상태를 변경할 수 없습니다\.|랠리즈 반영을 확인할 수 없습니다\.|시트에 반영할 수 없습니다\.|시트 수동 확인을 할 수 없습니다\.)$/.test(message)) return message;
  if (/^\d{1,6}건은 승인 후 수강 상태가 달라져 반영하지 않았습니다\. 요청을 다시 검토해 주세요\.$/.test(message)) return message;
  return fallback;
}

/** 인증 공급자의 알려진 코드만 번역하며, 공급자 원문을 화면으로 보내지 않는다. */
export function loginErrorMessage(error: { code?: string; message?: string }): string {
  if (error.code === "invalid_credentials" || error.message === "Invalid login credentials") {
    return "이메일 또는 비밀번호가 올바르지 않습니다.";
  }
  if (error.code === "email_not_confirmed" || error.message === "Email not confirmed") {
    return "이메일 인증이 필요합니다. 받은 인증 메일을 확인해주세요.";
  }
  if (error.code === "over_request_rate_limit" || error.code === "over_email_send_rate_limit") {
    return "로그인 요청이 많습니다. 잠시 후 다시 시도해 주세요.";
  }
  return "로그인하지 못했습니다. 잠시 후 다시 시도해 주세요.";
}
