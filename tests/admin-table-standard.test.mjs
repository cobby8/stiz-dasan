import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";

function read(path) {
  return readFileSync(new URL(path, import.meta.url), "utf8");
}

const adminShell = read("../src/app/admin/AdminShellClient.tsx");
const globalsCss = read("../src/app/globals.css");
const quickActionMenu = read("../src/components/admin/AdminQuickActionMenu.tsx");
const financeClient = read("../src/app/admin/finance/FinanceClient.tsx");
const financePage = read("../src/app/admin/finance/page.tsx");
const adminActions = read("../src/app/actions/admin.ts");

const quickActionClients = [
  "../src/app/admin/annual/AnnualAdminClient.tsx",
  "../src/app/admin/classes/ClassManagementClient.tsx",
  "../src/app/admin/coaches/CoachesAdminClient.tsx",
  "../src/app/admin/finance/FinanceClient.tsx",
  "../src/app/admin/finance/billing/BillingTemplateClient.tsx",
  "../src/app/admin/students/StudentManagementClient.tsx",
];

test("관리자 페이지는 전역 테이블 규칙 스코프를 한 번만 건다", () => {
  assert.match(adminShell, /admin-table-scope w-full min-w-0 flex-1/);
});

test("관리자 전역 테이블은 콤팩트 중앙 정렬 규칙을 공유한다", () => {
  assert.match(globalsCss, /\.admin-table-scope table/);
  assert.match(globalsCss, /table-layout:\s*fixed/);
  assert.match(globalsCss, /padding:\s*0\.5rem !important/);
  assert.match(globalsCss, /text-align:\s*center !important/);
  assert.match(globalsCss, /vertical-align:\s*middle !important/);
  assert.match(globalsCss, /justify-content:\s*center !important/);
  assert.match(globalsCss, /overflow-y:\s*visible/);
});

test("관리자 퀵액션 메뉴는 표 박스에 잘리지 않는 fixed floating 메뉴다", () => {
  assert.match(quickActionMenu, /fixed z-\[90\]/);
  assert.match(quickActionMenu, /flash_on/);
  assert.match(quickActionMenu, /pointerdown/);
  assert.match(quickActionMenu, /scroll", placeMenu, true/);
});

test("반복 관리 액션은 퀵액션 메뉴로 묶고 행별 삭제 확인 상태를 제거한다", () => {
  for (const path of quickActionClients) {
    const source = read(path);
    assert.match(source, /AdminQuickActionMenu/);
    assert.doesNotMatch(source, /deleteConfirm|setDeleteConfirm/);
  }
});

test("수납 결제 관리는 큰 안내 콘솔 대신 한 줄 작업바와 퀵액션을 쓴다", () => {
  assert.match(financeClient, /청구 작업/);
  assert.match(financeClient, /결제 설정 보기/);
  assert.match(financeClient, /청구 빠른 작업/);
  assert.doesNotMatch(financeClient, /청구서 발행 콘솔/);
  assert.doesNotMatch(financeClient, /다음 할 일/);
  assert.doesNotMatch(financeClient, /1\. 대상 확인/);
});

test("수납 목록은 원생명 아래 내부 설명과 청구번호를 노출하지 않는다", () => {
  // 2026-11-09 색상 정리 6단계: 글자색은 토큰(ink)으로 — 검사 뜻(이름만 한 줄)은 그대로
  assert.match(financeClient, /<span className="font-medium text-\[var\(--color-academy-ink\)\]">\{p\.studentName\}<\/span>/);
  assert.doesNotMatch(financeClient, /\{p\.description &&/);
  assert.doesNotMatch(financeClient, /\{p\.invoiceNo &&/);
  assert.doesNotMatch(financeClient, /\{p\.autoGenerated &&/);
});

test("수납 상태 변경과 삭제는 수퍼관리자에게만 열린다", () => {
  assert.match(financePage, /currentAdminRole=\{adminUser\.appUserRole\}/);
  assert.match(financeClient, /canManageCriticalFinance = currentAdminRole === "ADMIN"/);
  // 납부처리는 미납·연체에만(2026-11-08 «납부 처리» 창 전환)
  assert.match(financeClient, /canManageCriticalFinance && \["PENDING", "OVERDUE"\]\.includes\(p\.status\)/);
  assert.match(financeClient, /canManageCriticalFinance && p\.status === "PENDING"/);
  assert.match(financeClient, /canManageCriticalFinance && p\.status === "PAID"/);
  assert.match(adminActions, /async function requireFinanceOwner/);
  assert.match(adminActions, /export async function updatePaymentStatus[\s\S]*?await requireFinanceOwner\(\)/);
  assert.match(adminActions, /export async function recordBankTransferPayment[\s\S]*?const admin = await requireFinanceOwner\(\)/);
  assert.match(adminActions, /export async function deletePayment[\s\S]*?await requireFinanceOwner\(\)/);
  assert.match(adminActions, /export async function bulkUpdatePaymentStatus[\s\S]*?await requireFinanceOwner\(\)/);
});
